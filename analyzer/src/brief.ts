import type { Effect, EntryPoint, Finding, ModuleGraph, Operation, Risk, Step } from '../../schema/modulegraph.ts';
import { opLabel, reachIndex } from './rules.ts';

/**
 * The facts of a review as plain Markdown, generated from the graph. Any agent (or a person without the UI)
 * starts from this file instead of interpreting the JSON: everything here is computed, nothing is guessed.
 * The reviewing agent's job is reduced to judgment: which of these facts matter, and what to ask the author.
 */
export function brief(g: ModuleGraph, graphId: string, uiBase = 'http://127.0.0.1:5174'): string {
  const out: string[] = [];
  const s = g.source;
  const reach = reachIndex(g);
  const newFindings = g.findings.filter((f) => f.isNew || s.mode === 'snapshot');
  const errors = newFindings.filter((f) => f.severity === 'error');
  const warnings = newFindings.filter((f) => f.severity === 'warning');
  const partial = !!g.lazy;

  out.push(`# Review facts: ${s.title ?? `${s.mode} ${s.base ?? ''} → ${s.head ?? ''}`}`);
  out.push('');
  out.push(`Generated by ${g.generator} from ${s.mode === 'uncommitted' ? 'the working tree vs HEAD' : s.mode === 'snapshot' ? 'the current tree' : `${s.head}${s.workingTree ? ' with its uncommitted edits' : ''} vs ${s.base}`} in \`${s.repo}/${s.project}\`.`);
  if (s.analyzer) {
    const fw = s.analyzer.frameworks.map((f) => f.name).join(', ');
    // Entry points and side effects come from these adapters; anything else (custom platform code) needs profile rules.
    out.push(`Analyzed as ${s.analyzer.language}${fw ? ` with ${fw}` : ' (no framework adapters: only the profile\'s rules)'}.`);
  }
  out.push(`Change: ${g.review.stats.files} files, +${g.review.stats.linesAdded}/−${g.review.stats.linesRemoved}, ${g.review.stats.contractChanges} contract changes, ${g.review.stats.entryPointsAffected}${partial ? '+' : ''} entry points affected.`);
  out.push('');
  const incomplete = g.incomplete ?? [];
  const warned = `${warnings.length} new warning${warnings.length === 1 ? '' : 's'}`;
  const errored = `${errors.length} new error-level finding${errors.length > 1 ? 's' : ''}`;
  if (incomplete.length) {
    // "No findings" from an analysis that could not see the code is not a pass.
    out.push(errors.length
      ? `**Verdict: BLOCKING, and the analysis is INCOMPLETE.** ${errored} (\`--check\` fails), and more may be hidden: see "Analysis incomplete". ${warned}.`
      : `**Verdict: INCOMPLETE analysis, not a pass.** No new errors were found, but the analysis could not see everything (below), so \`--check\` fails. ${warned}.`);
    out.push('', '## Analysis incomplete', '');
    out.push('What follows may be missing side effects, entry points or changes. Fix these and analyze again, or review what they name by hand:', '');
    for (const issue of incomplete) {
      out.push(`- **${issue.kind}**${issue.side === 'base' ? ' (base revision)' : ''}: ${issue.message}`);
      for (const item of (issue.items ?? []).slice(0, 8)) out.push(`  - ${item}`);
      if ((issue.items?.length ?? 0) > 8) out.push(`  - … ${issue.items!.length - 8} more`);
      if (issue.hint) out.push(`  - What to do: ${issue.hint}`);
      if (issue.suggestion) {
        // The rule, ready to paste into the profile (the module-review skill writes it on a first run).
        out.push(`  - Add to the profile, \`${s.profile?.path ?? `~/.modulegraph/configs/${g.service}/modulegraph.config.json`}\`${s.profile?.exists ? '' : ` (create it with \`"service": "${g.service}"\`)`}:`, '');
        out.push('    ```json', ...issue.suggestion.split('\n').map((l) => `    ${l}`), '    ```', '');
      }
    }
  } else {
    out.push(errors.length
      ? `**Verdict: BLOCKING.** ${errored} (\`--check\` fails). ${warned}.`
      : `**Verdict: not blocked by checks.** No new errors (\`--check\` passes). ${warned}.`);
  }
  out.push('');
  out.push(s.intent
    ? `Stated intent (${s.intentSource ?? 'given'}): ${quote(s.intent)}`
    : 'Stated intent: **none**. The undisclosed-effect check did not run; ask the author what the change is for.');
  const ex = s.examples;
  if (ex) {
    out.push('');
    const covered = Object.values(g.operations).filter((op) => op.examples?.length).map((op) => `\`${opLabel(g, op.id)}\``);
    if (ex.kind === 'tests') {
      const n = ex.cases?.length ?? 0;
      out.push(n
        ? `Example data: ${n} test case${n === 1 ? '' : 's'} recorded **from unit tests (mocked dependencies)**, so inputs and outputs are what the tests' mocks made them, for ${covered.length} operation${covered.length === 1 ? '' : 's'} (${covered.slice(0, 8).join(', ')}${covered.length > 8 ? ', …' : ''}), from ${ex.specs?.length ?? 0} spec file${ex.specs?.length === 1 ? '' : 's'}: ${(ex.specs ?? []).map((f) => `\`${f}\``).join(', ')}.${ex.timedOut ? ` The run stopped after ${ex.timeoutSeconds} s (\`--tests-timeout\`): some cases are missing.` : ''}`
        : `Example data: none from unit tests (${ex.note ?? 'no case recorded'})${ex.specs?.length ? `; ran ${ex.specs.map((f) => `\`${f}\``).join(', ')}` : ''}.`);
    } else {
      out.push(`Example data: ${ex.cases?.length ?? 0} request${ex.cases?.length === 1 ? '' : 's'} of the scenario \`${ex.scenario}\`, for ${covered.length} operation${covered.length === 1 ? '' : 's'}.`);
    }
  }
  if (partial) {
    const st = g.lazy!.stats;
    out.push('');
    out.push(`Lazy analysis: ${st.entryPointsAnalyzed} of ${st.entryPointsKnown} flows analyzed (${g.lazy!.seeds.map((x) => `\`${label(g, x.id)}\``).join(', ')}). Reach counts are lower bounds.`);
  }

  // ---------- access control ----------
  // Before the module changes: a guard removed from a controller changes no operation, but opens every route on it.
  const pipelineFindings = newFindings.filter((f) => f.rule === 'access-control-changed' || f.rule === 'request-pipeline-changed');
  if (pipelineFindings.length) {
    out.push('', '## Access control and request pipeline: high risk', '');
    out.push('What runs before these handlers changed. Guards, middleware and auth metadata decide who may call them; interceptors, pipes and filters run around them. Each line applies to every entry point it lists.', '');
    for (const f of pipelineFindings) out.push(`- **${f.severity.toUpperCase()}** ${f.message}`);
  }

  // ---------- changes ----------
  // One section per independent change. Its parts are the changed operations only reached through its root.
  out.push('', '## Changes, riskiest first', '');
  const changes = g.review.changes;
  if (!changes.length) out.push('None: no module operation changed.');
  else if (changes.length < g.review.queue.length) {
    out.push(`${changes.length} change${changes.length > 1 ? 's' : ''} (${g.review.queue.length} changed operations). Each starts at its topmost changed operation; the operations under it are reached only through it.`, '');
  }
  const reason = new Map(g.review.queue.map((q) => [q.operation, q]));
  const section = (opId: string, heading: string, risk?: Risk) => {
    const op = g.operations[opId];
    const mod = g.modules[op.moduleId];
    const q = reason.get(opId)!;
    const entries = [...(reach.get(op.id) ?? [])].filter((id) => g.entryPoints[id]?.change !== 'removed');
    const own = risk && risk !== q.risk ? ` (with its parts; ${q.risk} on its own)` : '';
    out.push(`${heading} ${opLabel(g, op.id)}: ${risk ?? q.risk} risk${own}, ${op.change}${mod.owner ? `, owner ${mod.owner}` : ''}`);
    out.push('');
    const d = op.delta;
    if (d?.params) out.push(`- **Inputs**: (${sig(d.params.before)}) → (${sig(d.params.after)})`);
    if (d?.returns) {
      const before = new Set((d.returns.before.fields ?? []).map((f) => f.name));
      const after = new Set((d.returns.after.fields ?? []).map((f) => f.name));
      const plus = (d.returns.after.fields ?? []).filter((f) => !before.has(f.name)).map((f) => `+${f.name}: ${f.type}`);
      const minus = (d.returns.before.fields ?? []).filter((f) => !after.has(f.name)).map((f) => `−${f.name}`);
      const changedType = (d.returns.after.fields ?? []).filter((f) => before.has(f.name) && d.returns!.before.fields!.find((b) => b.name === f.name)!.type !== f.type)
        .map((f) => typeChange(f.name, d.returns!.before.fields!.find((b) => b.name === f.name)!.type, f.type));
      const parts = [...plus, ...minus, ...changedType];
      out.push(`- **Output** \`${d.returns.after.type}\`: ${parts.length ? parts.join(', ') : `${d.returns.before.type} → ${d.returns.after.type}`}`);
    }
    if (d?.effectsAdded.length || d?.effectsRemoved.length) {
      out.push(`- **Side effects**: ${[...d.effectsAdded.map((e) => `+${fx(e)}${direct(op, e) ? '' : ` (via ${viaWhom(g, op, e)})`}`), ...d.effectsRemoved.map((e) => `−${fx(e)}`)].join(', ')}`);
    }
    if (d?.callsAdded.length || d?.callsRemoved.length) {
      out.push(`- **Calls**: ${[...d.callsAdded.map((c) => `+${opLabel(g, c)}`), ...d.callsRemoved.map((c) => `−${opLabel(g, c)}`)].join(', ')}`);
    }
    const behaviour = behaviourChanges(g, op.id);
    if (behaviour.length) {
      out.push('- **Behaviour inside** (steps of this operation, base → head):');
      for (const b of behaviour) out.push(`  - ${b}`);
    }
    if (op.changes?.length) {
      const files = new Set(op.changes.map((c) => c.file)).size;
      out.push(`- **Code**: ${op.changes.length} function${op.changes.length > 1 ? 's' : ''} in ${files} file${files > 1 ? 's' : ''}: ${op.changes.map((c) => `\`${c.name}\` (${c.status}, +${c.added}/−${c.removed}, ${c.file}:${c.line})`).join('; ')}`);
    }
    if (d?.implementationOnly) {
      out.push(behaviour.length
        ? '- Same inputs, outputs and side effects, but **behaviour changed inside** (above): check who relied on the old behaviour.'
        : '- Implementation only: same inputs, outputs and side effects.');
    }
    out.push(`- **Reached from** ${entries.length}${partial && !op.lazy?.callersLoaded ? '+' : ''} entry point${entries.length === 1 ? '' : 's'}: ${list(entries.map((id) => `\`${label(g, id)}\``), 8)}`);
    out.push('');
  };
  changes.forEach((c, i) => {
    section(c.root, `### ${i + 1}.`, c.risk);
    if (c.alsoIn?.length) out.push(`Also reached through the change in ${c.alsoIn.map((r) => `\`${opLabel(g, r)}\``).join(', ')}, but other paths reach it too, so it is reviewed on its own.`, '');
    if (c.parts.length) {
      out.push(`Inside this change (reached only through ${opLabel(g, c.root)}): ${c.parts.map((p) => `${opLabel(g, p)} (${reason.get(p)!.risk})`).join(', ')}.`, '');
    }
    c.parts.forEach((p, k) => section(p, `#### ${i + 1}.${k + 1}.`));
  });

  // ---------- entry points ----------
  const added = Object.values(g.entryPoints).filter((e) => e.change === 'added');
  const removed = Object.values(g.entryPoints).filter((e) => e.change === 'removed');
  const modifiedEntries = Object.values(g.entryPoints).filter((e) => e.change === 'modified');
  if (added.length || removed.length || modifiedEntries.length) {
    out.push('## Entry points', '');
    for (const e of added) {
      // A new endpoint is a new door: say what guards it (or that nothing does).
      const guards = (e.pipeline ?? []).filter((p) => p.kind === 'guard' || p.kind === 'middleware' || p.kind === 'metadata').map((p) => `${p.name} (${p.scope})`);
      const guarded = e.pipeline ? ` Guarded by: ${guards.join(', ') || '**nothing**'}.` : '';
      out.push(`- **New**: \`${e.label}\` (${e.file}:${e.line}) → ${stepsOf(g, e)}. Side effects: ${e.effects.map(fx).join(', ') || 'none'}.${guarded}`);
    }
    for (const e of modifiedEntries) {
      const d = e.pipelineDelta;
      const pipe = d ? [...d.removed.map((x) => `−${x}`), ...d.added.map((x) => `+${x}`), ...d.changed.map((x) => `changed ${x}`)].join(', ') : '';
      out.push(`- **${pipe && !e.changes?.some((c) => c.role === 'handler') ? 'Pipeline changed' : 'Handler changed'}**: \`${e.label}\` (${e.file}:${e.line})${pipe ? `. Pipeline: ${pipe}` : ''}`);
    }
    for (const e of removed) out.push(`- **Removed**: \`${e.label}\``);
    out.push('');
  }
  const readWrites = Object.values(g.entryPoints).filter((e) => e.readOnly && e.effectsAdded?.some(isWrite));
  if (readWrites.length) {
    out.push('## Read-only entry points that now write', '');
    for (const e of readWrites) out.push(`- \`${e.label}\`: ${e.effectsAdded!.filter(isWrite).map((x) => `+${fx(x)}`).join(', ')}`);
    out.push('');
  }
  const changedEffects = Object.values(g.entryPoints).filter((e) => e.change !== 'added' && (e.effectsAdded?.length || e.effectsRemoved?.length));
  if (changedEffects.length) {
    out.push('## What each affected flow now touches differently', '');
    for (const e of changedEffects) {
      out.push(`- \`${e.label}\`: ${[...(e.effectsAdded ?? []).map((x) => `+${fx(x)}`), ...(e.effectsRemoved ?? []).map((x) => `−${fx(x)}`)].join(', ')}`);
    }
    out.push('');
  }

  // ---------- findings ----------
  out.push('## New findings (machine-checked)', '');
  if (!newFindings.length) out.push('None.');
  const hinted = new Set<string>();
  for (const fs of group(newFindings)) {
    const { rule, severity, hint } = fs[0];
    // A rule can fire at several levels (a new read is info, a new write a warning): one heading per level, hint once.
    const showHint = hint && !hinted.has(rule);
    hinted.add(rule);
    out.push(`- **${severity.toUpperCase()} ${rule}** ×${fs.length}${showHint ? ` (${hint.replace(/\s+/g, ' ')})` : ''}`);
    for (const f of fs.slice(0, 10)) out.push(`  - ${f.message}`);
    if (fs.length > 10) out.push(`  - … ${fs.length - 10} more`);
  }
  const old = g.findings.length - newFindings.length;
  if (old) out.push('', `${old} pre-existing finding${old > 1 ? 's' : ''} not caused by this change (not listed).`);
  out.push('');

  // ---------- descriptions the reviewer will see ----------
  // Changed operations and every module they call: the ones the reviewer meets in the flows. A description comes
  // from the method's doc comment, the API docs of an endpoint that hands to it (@ApiOperation), its class's doc
  // comment, or the profile. What has none of those is listed: the changed ones first, as a required step.
  const met = new Set<string>();
  for (const q of g.review.queue) {
    met.add(q.operation);
    for (const step of g.scopes[q.operation]?.steps ?? []) if (step.target) met.add(step.target);
  }
  const metOps = [...met].map((id) => g.operations[id]).filter((op) => op && op.change !== 'removed');
  const undescribed = metOps.filter((op) => !op.summary);
  const changedUndescribed = undescribed.filter((op) => op.change !== 'unchanged');
  const fromDocs = metOps.filter((op) => op.summarySource === 'api' || op.summarySource === 'class');
  const profilePath = s.profile?.path ?? `~/.modulegraph/configs/${g.service}/modulegraph.config.json`;
  if (undescribed.length || fromDocs.length) {
    out.push('## Needs a description', '');
    if (fromDocs.length) {
      out.push(`Described from the code's own documentation (no doc comment on the method): ${fromDocs.map((op) => `\`${op.id}\` (${op.summarySource === 'api' ? op.summaryFrom ?? 'API docs' : "its class's doc comment"})`).join(', ')}.`, '');
    }
    if (!undescribed.length) out.push('Every operation this review meets has a description.', '');
  }
  if (undescribed.length) {
    out.push(`No doc comment, no API docs, nothing in the profile. Read each and write one or two sentences (what it does, not how) into the profile, \`${profilePath}\`${s.profile?.exists ? '' : ' (it does not exist yet: create it with `"service": "' + g.service + '"`)'}, under \`modules.overrides.<Class>.operations.<method>\`, then refresh:`, '');
    // The exact JSON, keyed by class name (not the shorter name the change headlines show), for every required one.
    const byClass = new Map<string, string[]>();
    for (const op of changedUndescribed.length ? changedUndescribed : undescribed.slice(0, 1)) {
      const cls = g.modules[op.moduleId]?.className ?? op.moduleId;
      byClass.set(cls, [...(byClass.get(cls) ?? []), op.name]);
    }
    const json = [...byClass].map(([cls, names]) => `    "${cls}": { "operations": { ${names.map((n) => `"${n}": "…"`).join(', ')} } }`).join(',\n');
    out.push('```json', `"modules": {\n  "overrides": {\n${json}\n  }\n}`, '```', '');
    const context = (op: (typeof undescribed)[number]) => (op.context ? `; only called through \`${op.context.from}\` ("${short(op.context.summary, 90)}"): say what this one adds` : '');
    if (changedUndescribed.length) {
      out.push(`**Required: ${changedUndescribed.length} changed operation${changedUndescribed.length > 1 ? 's' : ''}** (the reviewer starts here):`, '');
      for (const op of changedUndescribed) out.push(`- \`${op.id}\` (${op.file}:${op.line}), ${op.change}${context(op)}`);
      out.push('');
    }
    const called = undescribed.filter((op) => op.change === 'unchanged');
    if (called.length) {
      out.push(`${changedUndescribed.length ? 'Also met in the flows' : 'Met in the flows'} (called by the change):`, '');
      for (const op of called.slice(0, 20)) out.push(`- \`${op.id}\` (${op.file}:${op.line})${context(op)}`);
      if (called.length > 20) out.push(`- … ${called.length - 20} more`);
      out.push('');
    }
  } else if (fromDocs.length) out.push('');
  const unmatched = s.profile?.unmatched ?? [];
  if (unmatched.length) {
    out.push('## Profile descriptions not applied', '');
    out.push(`\`${profilePath}\` describes ${unmatched.length === 1 ? 'something' : `${unmatched.length} things`} this service does not have, so ${unmatched.length === 1 ? 'it shows' : 'they show'} nowhere. Key them by class name and method, as in the JSON above:`, '');
    for (const u of unmatched) out.push(`- ${u}`);
    out.push('');
  }

  // ---------- routing and links ----------
  out.push('## Request review from', '');
  out.push(g.review.reviewers.length ? g.review.reviewers.join(', ') : 'No owners configured for the changed modules.');
  out.push('');
  out.push('## Open in the UI', '');
  out.push(`Served live by \`modulegraph review\` while it runs. \`modulegraph open ${graphId}\` serves it live again later (refresh and done work) while the repo and its branches are on this machine.`, '');
  const top = g.review.changes[0]?.root;
  if (top) out.push(`- Zoom out from the riskiest change: ${uiBase}/#g=${graphId}&v=impact&op=${encodeURIComponent(top)}&d=1`);
  const firstFlow = g.lazy?.seeds[0]?.id ?? (top ? [...(reach.get(top) ?? [])][0] : undefined);
  if (firstFlow) out.push(`- A flow through it: ${uiBase}/#g=${graphId}&v=flow&t=${encodeURIComponent(firstFlow)}${top ? `&f=${encodeURIComponent(top)}` : ''}`);
  out.push('');
  return out.join('\n');
}

/** "status gains "pending_review"" for literal unions; "a: X → Y" otherwise. */
function typeChange(name: string, before: string, after: string): string {
  const values = (t: string) => new Set(t.match(/"[^"]*"/g) ?? []);
  const b = values(before);
  const a = values(after);
  if (a.size || b.size) {
    const gained = [...a].filter((v) => !b.has(v));
    const lost = [...b].filter((v) => !a.has(v));
    if (gained.length || lost.length) {
      return `${name} ${[gained.length && `gains ${gained.join(', ')}`, lost.length && `loses ${lost.join(', ')}`].filter(Boolean).join(' and ')} (callers that branch on it must handle this)`;
    }
  }
  return `${name}: ${before} → ${after}`;
}

/** Step-level differences of an operation: new/removed calls and side effects, and guards that changed. */
function behaviourChanges(g: ModuleGraph, opId: string): string[] {
  const scope = g.scopes[opId];
  if (!scope || g.operations[opId].change === 'added') return [];
  const what = (s: Step) => (s.target ? `call ${opLabel(g, s.target)}` : `${s.effect!.kind} \`${s.effect!.target}\``);
  const where = (s: Step) => [s.condition && `only ${when(s.condition)}`, s.loop && 'once per item', s.via && s.via !== opId && `in ${s.via}`].filter(Boolean).join(', ');
  const out: string[] = [];
  for (const s of scope.steps) {
    if (s.delta === 'added') out.push(`NEW ${what(s)}${where(s) ? ` (${where(s)})` : ''}`);
    else if (s.conditionBefore !== undefined) {
      out.push(`GUARD CHANGED ${what(s)}: now ${s.condition ? `only ${when(s.condition)}` : 'always'}; before: ${s.conditionBefore ? `only ${when(s.conditionBefore)}` : 'always'}`);
    }
  }
  for (const s of scope.removedSteps ?? []) out.push(`REMOVED ${what(s)}${where(s) ? ` (was ${where(s)})` : ''}`);
  return out;
}

function stepsOf(g: ModuleGraph, e: EntryPoint): string {
  const steps = g.scopes[e.id]?.steps ?? [];
  return steps.length ? steps.map((s) => (s.target ? opLabel(g, s.target) : `${s.effect!.kind} ${s.effect!.target}`)).join(', ') : 'not analyzed';
}

/** Findings grouped by severity and rule, most severe first. */
function group(fs: Finding[]): Finding[][] {
  const order = { error: 0, warning: 1, info: 2 };
  const m = new Map<string, Finding[]>();
  for (const f of [...fs].sort((a, b) => order[a.severity] - order[b.severity])) {
    const key = `${f.severity} ${f.rule}`;
    m.set(key, [...(m.get(key) ?? []), f]);
  }
  return [...m.values()];
}

/** "if (x)" → "when x", "unless (x)" → "when not x", so guards read as plain conditions. */
const when = (c: string) => c.split(' and ').map((p) => p.replace(/^if \((.*)\)$/, 'when `$1`').replace(/^unless \((.*)\)$/, 'when not `$1`')).join(' and ');
const label = (g: ModuleGraph, id: string) => g.entryPoints[id]?.label ?? opLabel(g, id);
const fx = (e: Effect) => `${e.kind} \`${e.target}\``;
const isWrite = (e: Effect) => e.kind !== 'db.read' && e.kind !== 'http';
const direct = (op: Operation, e: Effect) => op.directEffects.some((x) => x.kind === e.kind && x.target === e.target);
/** The operation this one calls that brings the effect: named when it is in the same module, else "a submodule". */
function viaWhom(g: ModuleGraph, op: Operation, e: Effect): string {
  const callee = op.calls.map((c) => g.operations[c]).find((c) => c?.effects.some((x) => x.kind === e.kind && x.target === e.target));
  if (!callee) return 'a submodule';
  return callee.moduleId === op.moduleId ? `${g.modules[op.moduleId]?.name ?? op.moduleId}.${callee.name}` : 'a submodule';
}
const sig = (ps: { name: string; type: string }[]) => ps.map((p) => `${p.name}: ${p.type}`).join(', ');
const list = (xs: string[], n: number) => (xs.length > n ? `${xs.slice(0, n).join(', ')}, … ${xs.length - n} more` : xs.join(', ') || 'none found');
const quote = (t: string) => `“${t.trim().replace(/\s+/g, ' ').slice(0, 600)}”`;

/** At most `max` characters, with an ellipsis. */
function short(text: string, max: number): string {
  return text.length > max ? `${text.slice(0, max - 1)}…` : text;
}
