import type { Effect, EntryPoint, Finding, ModuleGraph, Operation, Step } from '../../schema/modulegraph.ts';
import { opLabel, reachIndex } from './rules.ts';

/**
 * The facts of a review as plain Markdown, generated from the graph. Any agent (or a person without the UI)
 * starts from this file instead of interpreting the JSON: everything here is computed, nothing is guessed.
 * The reviewing agent's job is reduced to judgment: which of these facts matter, and what to ask the author.
 */
export function brief(g: ModuleGraph, graphId: string, uiBase = 'http://localhost:5173'): string {
  const out: string[] = [];
  const s = g.source;
  const reach = reachIndex(g);
  const newFindings = g.findings.filter((f) => f.isNew || s.mode === 'snapshot');
  const errors = newFindings.filter((f) => f.severity === 'error');
  const warnings = newFindings.filter((f) => f.severity === 'warning');
  const partial = !!g.lazy;

  out.push(`# Review facts: ${s.title ?? `${s.mode} ${s.base ?? ''} → ${s.head ?? ''}`}`);
  out.push('');
  out.push(`Generated by ${g.generator} from ${s.mode === 'uncommitted' ? 'the working tree vs HEAD' : s.mode === 'snapshot' ? 'the current tree' : `${s.head}${s.workingTree ? ' with its uncommitted edits' : ''} vs ${s.base}`} in \`${s.repo}/${s.project}\`.`);
  if (s.analyzer) {
    const fw = s.analyzer.frameworks.map((f) => f.name).join(', ');
    // Entry points and side effects come from these adapters; anything else (custom platform code) needs profile rules.
    out.push(`Analyzed as ${s.analyzer.language}${fw ? ` with ${fw}` : ' (no framework adapters: only the profile\'s rules)'}.`);
  }
  out.push(`Change: ${g.review.stats.files} files, +${g.review.stats.linesAdded}/−${g.review.stats.linesRemoved}, ${g.review.stats.contractChanges} contract changes, ${g.review.stats.entryPointsAffected}${partial ? '+' : ''} entry points affected.`);
  out.push('');
  out.push(errors.length
    ? `**Verdict: BLOCKING.** ${errors.length} new error-level finding${errors.length > 1 ? 's' : ''} (\`--check\` fails). ${warnings.length} new warnings.`
    : `**Verdict: not blocked by checks.** No new errors (\`--check\` passes). ${warnings.length} new warning${warnings.length === 1 ? '' : 's'}.`);
  out.push('');
  out.push(s.intent
    ? `Stated intent (${s.intentSource ?? 'given'}): ${quote(s.intent)}`
    : 'Stated intent: **none**. The undisclosed-effect check did not run; ask the author what the change is for.');
  if (partial) {
    const st = g.lazy!.stats;
    out.push('');
    out.push(`Lazy analysis: ${st.entryPointsAnalyzed} of ${st.entryPointsKnown} flows analyzed (${g.lazy!.seeds.map((x) => `\`${label(g, x.id)}\``).join(', ')}). Reach counts are lower bounds.`);
  }

  // ---------- contract changes ----------
  out.push('', '## Contract changes, riskiest first', '');
  if (!g.review.queue.length) out.push('None: no module operation changed.');
  g.review.queue.forEach((q, i) => {
    const op = g.operations[q.operation];
    const mod = g.modules[op.moduleId];
    const entries = [...(reach.get(op.id) ?? [])].filter((id) => g.entryPoints[id]?.change !== 'removed');
    out.push(`### ${i + 1}. ${opLabel(g, op.id)}: ${q.risk} risk, ${op.change}${mod.owner ? `, owner ${mod.owner}` : ''}`);
    out.push('');
    const d = op.delta;
    if (d?.params) out.push(`- **Inputs**: (${sig(d.params.before)}) → (${sig(d.params.after)})`);
    if (d?.returns) {
      const before = new Set((d.returns.before.fields ?? []).map((f) => f.name));
      const after = new Set((d.returns.after.fields ?? []).map((f) => f.name));
      const plus = (d.returns.after.fields ?? []).filter((f) => !before.has(f.name)).map((f) => `+${f.name}: ${f.type}`);
      const minus = (d.returns.before.fields ?? []).filter((f) => !after.has(f.name)).map((f) => `−${f.name}`);
      const changedType = (d.returns.after.fields ?? []).filter((f) => before.has(f.name) && d.returns!.before.fields!.find((b) => b.name === f.name)!.type !== f.type)
        .map((f) => typeChange(f.name, d.returns!.before.fields!.find((b) => b.name === f.name)!.type, f.type));
      const parts = [...plus, ...minus, ...changedType];
      out.push(`- **Output** \`${d.returns.after.type}\`: ${parts.length ? parts.join(', ') : `${d.returns.before.type} → ${d.returns.after.type}`}`);
    }
    if (d?.effectsAdded.length || d?.effectsRemoved.length) {
      out.push(`- **Side effects**: ${[...d.effectsAdded.map((e) => `+${fx(e)}${direct(op, e) ? '' : ` (via ${viaWhom(g, op, e)})`}`), ...d.effectsRemoved.map((e) => `−${fx(e)}`)].join(', ')}`);
    }
    if (d?.callsAdded.length || d?.callsRemoved.length) {
      out.push(`- **Calls**: ${[...d.callsAdded.map((c) => `+${opLabel(g, c)}`), ...d.callsRemoved.map((c) => `−${opLabel(g, c)}`)].join(', ')}`);
    }
    const behaviour = behaviourChanges(g, op.id);
    if (behaviour.length) {
      out.push('- **Behaviour inside** (steps of this operation, base → head):');
      for (const b of behaviour) out.push(`  - ${b}`);
    }
    if (op.changes?.length) {
      const files = new Set(op.changes.map((c) => c.file)).size;
      out.push(`- **Code**: ${op.changes.length} function${op.changes.length > 1 ? 's' : ''} in ${files} file${files > 1 ? 's' : ''}: ${op.changes.map((c) => `\`${c.name}\` (${c.status}, +${c.added}/−${c.removed}, ${c.file}:${c.line})`).join('; ')}`);
    }
    if (d?.implementationOnly) {
      out.push(behaviour.length
        ? '- Same inputs, outputs and side effects, but **behaviour changed inside** (above): check who relied on the old behaviour.'
        : '- Implementation only: same inputs, outputs and side effects.');
    }
    out.push(`- **Reached from** ${entries.length}${partial && !op.lazy?.callersLoaded ? '+' : ''} entry point${entries.length === 1 ? '' : 's'}: ${list(entries.map((id) => `\`${label(g, id)}\``), 8)}`);
    out.push('');
  });

  // ---------- entry points ----------
  const added = Object.values(g.entryPoints).filter((e) => e.change === 'added');
  const removed = Object.values(g.entryPoints).filter((e) => e.change === 'removed');
  const modifiedEntries = Object.values(g.entryPoints).filter((e) => e.change === 'modified');
  if (added.length || removed.length || modifiedEntries.length) {
    out.push('## Entry points', '');
    for (const e of added) out.push(`- **New**: \`${e.label}\` (${e.file}:${e.line}) → ${stepsOf(g, e)}. Side effects: ${e.effects.map(fx).join(', ') || 'none'}`);
    for (const e of modifiedEntries) out.push(`- **Handler changed**: \`${e.label}\` (${e.file}:${e.line})`);
    for (const e of removed) out.push(`- **Removed**: \`${e.label}\``);
    out.push('');
  }
  const readWrites = Object.values(g.entryPoints).filter((e) => e.readOnly && e.effectsAdded?.some(isWrite));
  if (readWrites.length) {
    out.push('## Read-only entry points that now write', '');
    for (const e of readWrites) out.push(`- \`${e.label}\`: ${e.effectsAdded!.filter(isWrite).map((x) => `+${fx(x)}`).join(', ')}`);
    out.push('');
  }
  const changedEffects = Object.values(g.entryPoints).filter((e) => e.change !== 'added' && (e.effectsAdded?.length || e.effectsRemoved?.length));
  if (changedEffects.length) {
    out.push('## What each affected flow now touches differently', '');
    for (const e of changedEffects) {
      out.push(`- \`${e.label}\`: ${[...(e.effectsAdded ?? []).map((x) => `+${fx(x)}`), ...(e.effectsRemoved ?? []).map((x) => `−${fx(x)}`)].join(', ')}`);
    }
    out.push('');
  }

  // ---------- findings ----------
  out.push('## New findings (machine-checked)', '');
  if (!newFindings.length) out.push('None.');
  const hinted = new Set<string>();
  for (const fs of group(newFindings)) {
    const { rule, severity, hint } = fs[0];
    // A rule can fire at several levels (a new read is info, a new write a warning): one heading per level, hint once.
    const showHint = hint && !hinted.has(rule);
    hinted.add(rule);
    out.push(`- **${severity.toUpperCase()} ${rule}** ×${fs.length}${showHint ? ` (${hint.replace(/\s+/g, ' ')})` : ''}`);
    for (const f of fs.slice(0, 10)) out.push(`  - ${f.message}`);
    if (fs.length > 10) out.push(`  - … ${fs.length - 10} more`);
  }
  const old = g.findings.length - newFindings.length;
  if (old) out.push('', `${old} pre-existing finding${old > 1 ? 's' : ''} not caused by this change (not listed).`);
  out.push('');

  // ---------- routing and links ----------
  out.push('## Request review from', '');
  out.push(g.review.reviewers.length ? g.review.reviewers.join(', ') : 'No owners configured for the changed modules.');
  out.push('');
  out.push('## Open in the UI', '');
  const top = g.review.queue[0]?.operation;
  if (top) out.push(`- Zoom out from the riskiest change: ${uiBase}/#g=${graphId}&v=impact&op=${encodeURIComponent(top)}&d=1`);
  const firstFlow = g.lazy?.seeds[0]?.id ?? (top ? [...(reach.get(top) ?? [])][0] : undefined);
  if (firstFlow) out.push(`- A flow through it: ${uiBase}/#g=${graphId}&v=flow&t=${encodeURIComponent(firstFlow)}${top ? `&f=${encodeURIComponent(top)}` : ''}`);
  out.push('');
  return out.join('\n');
}

/** "status gains "pending_review"" for literal unions; "a: X → Y" otherwise. */
function typeChange(name: string, before: string, after: string): string {
  const values = (t: string) => new Set(t.match(/"[^"]*"/g) ?? []);
  const b = values(before);
  const a = values(after);
  if (a.size || b.size) {
    const gained = [...a].filter((v) => !b.has(v));
    const lost = [...b].filter((v) => !a.has(v));
    if (gained.length || lost.length) {
      return `${name} ${[gained.length && `gains ${gained.join(', ')}`, lost.length && `loses ${lost.join(', ')}`].filter(Boolean).join(' and ')} (callers that branch on it must handle this)`;
    }
  }
  return `${name}: ${before} → ${after}`;
}

/** Step-level differences of an operation: new/removed calls and side effects, and guards that changed. */
function behaviourChanges(g: ModuleGraph, opId: string): string[] {
  const scope = g.scopes[opId];
  if (!scope || g.operations[opId].change === 'added') return [];
  const what = (s: Step) => (s.target ? `call ${opLabel(g, s.target)}` : `${s.effect!.kind} \`${s.effect!.target}\``);
  const where = (s: Step) => [s.condition && `only ${when(s.condition)}`, s.loop && 'once per item', s.via && s.via !== opId && `in ${s.via}`].filter(Boolean).join(', ');
  const out: string[] = [];
  for (const s of scope.steps) {
    if (s.delta === 'added') out.push(`NEW ${what(s)}${where(s) ? ` (${where(s)})` : ''}`);
    else if (s.conditionBefore !== undefined) {
      out.push(`GUARD CHANGED ${what(s)}: now ${s.condition ? `only ${when(s.condition)}` : 'always'}; before: ${s.conditionBefore ? `only ${when(s.conditionBefore)}` : 'always'}`);
    }
  }
  for (const s of scope.removedSteps ?? []) out.push(`REMOVED ${what(s)}${where(s) ? ` (was ${where(s)})` : ''}`);
  return out;
}

function stepsOf(g: ModuleGraph, e: EntryPoint): string {
  const steps = g.scopes[e.id]?.steps ?? [];
  return steps.length ? steps.map((s) => (s.target ? opLabel(g, s.target) : `${s.effect!.kind} ${s.effect!.target}`)).join(', ') : 'not analyzed';
}

/** Findings grouped by severity and rule, most severe first. */
function group(fs: Finding[]): Finding[][] {
  const order = { error: 0, warning: 1, info: 2 };
  const m = new Map<string, Finding[]>();
  for (const f of [...fs].sort((a, b) => order[a.severity] - order[b.severity])) {
    const key = `${f.severity} ${f.rule}`;
    m.set(key, [...(m.get(key) ?? []), f]);
  }
  return [...m.values()];
}

/** "if (x)" → "when x", "unless (x)" → "when not x", so guards read as plain conditions. */
const when = (c: string) => c.split(' and ').map((p) => p.replace(/^if \((.*)\)$/, 'when `$1`').replace(/^unless \((.*)\)$/, 'when not `$1`')).join(' and ');
const label = (g: ModuleGraph, id: string) => g.entryPoints[id]?.label ?? opLabel(g, id);
const fx = (e: Effect) => `${e.kind} \`${e.target}\``;
const isWrite = (e: Effect) => e.kind !== 'db.read' && e.kind !== 'http';
const direct = (op: Operation, e: Effect) => op.directEffects.some((x) => x.kind === e.kind && x.target === e.target);
/** The operation this one calls that brings the effect: named when it is in the same module, else "a submodule". */
function viaWhom(g: ModuleGraph, op: Operation, e: Effect): string {
  const callee = op.calls.map((c) => g.operations[c]).find((c) => c?.effects.some((x) => x.kind === e.kind && x.target === e.target));
  if (!callee) return 'a submodule';
  return callee.moduleId === op.moduleId ? `${g.modules[op.moduleId]?.name ?? op.moduleId}.${callee.name}` : 'a submodule';
}
const sig = (ps: { name: string; type: string }[]) => ps.map((p) => `${p.name}: ${p.type}`).join(', ');
const list = (xs: string[], n: number) => (xs.length > n ? `${xs.slice(0, n).join(', ')}, … ${xs.length - n} more` : xs.join(', ') || 'none found');
const quote = (t: string) => `“${t.trim().replace(/\s+/g, ' ').slice(0, 600)}”`;
